def run_page(*, series: RunSeries, summary: Record, log_path: str, generated: float) -> Page:
    """The page for a workload log.

    ``summary`` is the report's own (:func:`treehawk.report.build_report`):
    the recorded one when the run finished, recomputed from the samples when
    it did not. Whether it finished is read from ``series``, which holds only
    what the log recorded.
    """
    header = series.header
    target = target_of(header)
    started = epoch_of(header.get("started_at"))
    return Page(
        title=f"{truncate(target, width=60)} · treehawk report",
        kind=str(header.get("mode") or "run"),
        headline=target,
        status=_status(series=series, summary=summary),
        span=_span(series=series, summary=summary, started=started),
        figures=_figures(series=series, summary=summary),
        notices=_notices(series=series, summary=summary),
        sections=[
            Section(
                title="Timeline",
                intro=(
                    "Hover over a chart to read every series at that moment. "
                    "Time runs from the first sample to the last."
                ),
                charts=_charts(series=series, summary=summary, started=started),
            ),
            *_consumers(summary),
            *_tracks(series),
            Section(title="Run details", facts=_facts(series=series, summary=summary, started=started, log=log_path)),
        ],
        footer=f"Generated by treehawk {__version__} on {stamp(generated)} from {log_path}",
    )


# -- the top of the page -------------------------------------------------------


def _status(*, series: RunSeries, summary: Record) -> list[Notice]:
    header = series.header
    host = as_mapping(header.get("host"))
    chips: list[Notice] = []
    exit_chip = _exit_chip(series=series, summary=summary)
    if exit_chip is not None:
        chips.append(exit_chip)
    chips.extend(
        (
            Notice(level=Level.NOTE, title=str(host.get("hostname", "?")), text="the machine it ran on"),
            Notice(level=Level.NOTE, title=platform_name(host.get("platform"))),
            Notice(level=Level.NOTE, title=f"every {series.interval:g}s", text="the sampling interval asked for"),
        )
    )
    if not series.has_per_process:
        chips.append(Notice(level=Level.NOTE, title="totals only", text="logged without per-process detail"))
    return chips


def _exit_chip(*, series: RunSeries, summary: Record) -> Notice | None:
    if not series.summary:
        return Notice(level=Level.WARNING, title="interrupted", text="the log ends without a summary")
    code = as_int(summary.get("exit_code"))
    if code is None:
        return None
    if code == 0:
        return Notice(level=Level.GOOD, title="exit 0", text="the command succeeded")
    return Notice(level=Level.CRITICAL, title=_exit_text(code))


def _exit_text(code: int) -> str:
    """An exit code as a person says it: ``exit 2``, or ``killed by SIGTERM``."""
    if code >= 0:
        return f"exit {code}"
    try:
        return f"killed by {signal.Signals(-code).name}"
    except ValueError:
        return f"killed by signal {-code}"


def _span(*, series: RunSeries, summary: Record, started: float | None) -> list[Figure]:
    duration = series.duration
    asleep = series.asleep_s
    if started is None:
        start = Figure(label="Started", value="-")
        end = Figure(label="Ended", value="-")
    else:
        start = Figure(label="Started", value=clock(started), detail=day(started))
        end = Figure(label="Ended", value=clock(started + duration), detail=day(started + duration))
    detail = f"{format_duration_compact(asleep)} of it asleep" if asleep else f"{summary.get('samples', 0)} samples"
    return [start, end, Figure(label="Duration", value=format_duration_compact(duration), detail=detail)]


def _figures(*, series: RunSeries, summary: Record) -> list[Figure]:
    ncpu = series.ncpu
    peak_cpu = as_float(summary.get("peak_cpu_percent"))
    mean_cpu = as_float(summary.get("mean_cpu_percent"))
    memory = peak_memory_reading(summary=summary, header=series.header)
    rss = as_float(summary.get("peak_rss_bytes"))
    memory_detail = memory.label if memory.label == "rss" else f"{memory.label} · rss {format_bytes(rss)}"
    processes = as_int(summary.get("total_procs_seen")) or len(series.tracks)
    return [
        Figure(
            label="Peak CPU",
            value=format_percent(peak_cpu),
            detail=f"{(peak_cpu or 0) / 100:.1f} of {ncpu} cores" if peak_cpu is not None else "",
        ),
        Figure(
            label="Mean CPU",
            value=format_percent(mean_cpu),
            detail=f"{(mean_cpu or 0) / 100:.1f} cores on average" if mean_cpu is not None else "",
        ),
        Figure(
            label="CPU time",
            value=format_duration_compact(as_float(summary.get("cpu_seconds_used"))),
            detail="user + system, every process",
        ),
        Figure(label="Peak memory", value=format_bytes(memory.value), detail=memory_detail),
        Figure(label="Processes", value=str(processes), detail=f"up to {summary.get('peak_n_procs', '?')} at once"),
    ]


def _notices(*, series: RunSeries, summary: Record) -> list[Notice]:
    header = series.header
    notices: list[Notice] = []
    code = as_int(summary.get("exit_code"))
    if code:
        notices.append(
            Notice(
                level=Level.CRITICAL,
                title=f"The command did not succeed: {_exit_text(code)}",
                text="The figures cover the run up to the moment it ended.",
            )
        )
    if not series.summary:
        notices.append(
            Notice(
                level=Level.WARNING,
                title="The log ends without a summary",
                text=(
                    "The run was interrupted, or treehawk was stopped before it could finish. "
                    "The figures here are recomputed from the samples that were written."
                ),
            )
        )
    overruns = as_int(summary.get("overruns")) or len(series.overrun_t)
    if overruns:
        notices.append(
            Notice(
                level=Level.WARNING,
                title=(
                    f"{overruns} of {summary.get('samples', len(series.t))} samples took longer "
                    f"than the {series.interval:g}s interval"
                ),
                text=(
                    "They are marked along the bottom of the CPU chart. Sampling this many processes "
                    "needs more time; a longer interval (--interval) gives it room."
                ),
            )
        )
    if series.sleeps:
        notices.append(
            Notice(
                level=Level.NOTE,
                title=f"The machine slept for {format_seconds(series.asleep_s)}",
                text=(
                    "Sleep is counted in the duration and shaded on the charts. "
                    "Nothing ran, and nothing was measured, while it slept."
                ),
            )
        )
    client = container_client_of(header=header, summary=summary)
    if client is not None:
        notices.append(
            Notice(
                level=Level.NOTE,
                title=f"{client} is a container client",
                text=(
                    "Its containers run under the container engine, not in the tracked process tree, "
                    "so their CPU and memory are not in these figures."
                ),
            )
        )
    if not series.has_per_process:
        notices.append(
            Notice(
                level=Level.NOTE,
                title="Logged without per-process detail",
                text="The run used --aggregate-only, so there are totals but no process tracks.",
            )
        )
    notices.extend(Notice(level=Level.NOTE, title=str(note)) for note in as_sequence(header.get("notes")))
    return notices


# -- the timeline --------------------------------------------------------------


def _charts(*, series: RunSeries, summary: Record, started: float | None) -> list[Chart]:
    duration = series.duration
    columns: list[list[float | None]] = [
        list(series.cpu_percent),
        _floats(series.rss),
        _floats(series.pss),
        _floats(series.group_memory),
        [float(count) for count in series.n_procs],
    ]
    thinned = len(series.t) > HTML.chart_points
    x, columns = thin(x=series.t, columns=columns)
    width = duration / HTML.chart_points if thinned else series.interval
    x, columns = with_breaks(x=x, columns=columns, gap=max(width, series.interval) * HTML.gap_points)
    cpu, rss, fair, group, alive = columns
    axis = Axis(
        x=[moment / duration if duration else 0.0 for moment in x],
        when=[_when(moment, started=started) for moment in x],
        ticks=elapsed_ticks(duration),
        bands=[Band(start=begin / duration, end=end / duration, label="asleep") for begin, end in series.sleeps]
        if duration
        else [],
    )
    resolution = f" Each point is the peak of {format_seconds(width)}." if thinned else ""
    charts = [_cpu_chart(series=series, summary=summary, values=cpu, axis=axis, resolution=resolution)]
    memory = _memory_chart(series=series, columns=(rss, fair, group), axis=axis, resolution=resolution)
    if memory is not None:
        charts.append(memory)
    charts.append(
        chart(
            axis=axis,
            title="Processes alive",
            unit=Unit.COUNT,
            peak=peak_of(alive),
            lines=[
                Line(
                    label="processes",
                    color="ink-2",
                    values=alive,
                    readouts=["-" if value is None else f"{value:g}" for value in alive],
                    summary=f"{peak_of(alive) or 0:g} peak",
                    fill=True,
                    step=True,
                )
            ],
            caption=f"How many of the workload's processes were running at each sample.{resolution}",
        )
    )
    return charts


def _cpu_chart(
    *,
    series: RunSeries,
    summary: Record,
    values: list[float | None],
    axis: Axis,
    resolution: str,
) -> Chart:
    ncpu = series.ncpu
    capacity = ncpu * 100.0
    peak = peak_of(values)
    near_capacity = (peak or 0.0) >= capacity * HTML.capacity_share
    caption = f"100% is one core fully busy; this machine has {ncpu} cores, {capacity:g}% in all."
    if series.overrun_t:
        caption += " Ticks along the bottom mark samples that came late."
    if series.sleeps:
        caption += " Shaded stretches are sleep."
    result = chart(
        axis=axis,
        title="CPU",
        unit=Unit.PERCENT,
        peak=capacity if near_capacity else peak,
        lines=[
            Line(
                label="cpu",
                color="s1",
                values=values,
                readouts=[format_percent(value) for value in values],
                summary=f"{format_percent(peak)} peak",
                fill=True,
            )
        ],
        caption=caption + resolution,
    )
    mean = as_float(summary.get("mean_cpu_percent"))
    if mean is not None:
        result.rules.append(Rule(value=mean, label=f"mean {format_percent(mean)}"))
    if near_capacity:
        result.rules.append(Rule(value=capacity, label=f"all {ncpu} cores"))
    duration = series.duration
    if duration:
        result.marks.extend(
            Mark(position=moment / duration, level=Level.WARNING, label="this sample took longer than the interval")
            for moment in series.overrun_t
        )
    return result


def _memory_chart(
    *,
    series: RunSeries,
    columns: tuple[list[float | None], list[float | None], list[float | None]],
    axis: Axis,
    resolution: str,
) -> Chart | None:
    """Every memory measure the log carries - those, and no others."""
    measure = memory_measure(series.header)
    rss, fair, group = columns
    candidates = (("rss (summed)", "s2", rss), (measure.long, "s3", fair), ("cgroup", "s6", group))
    present = [(label, color, values) for label, color, values in candidates if peak_of(values) is not None]
    if not present:
        return None
    subtitle = memory_subtitle(
        measure=measure,
        rss=peak_of(rss) is not None,
        fair=peak_of(fair) is not None,
        group=peak_of(group) is not None,
    )
    return chart(
        axis=axis,
        title="Memory",
        unit=Unit.BYTES,
        peak=max(peak_of(values) or 0.0 for _label, _color, values in present),
        lines=[
            Line(
                label=label,
                color=color,
                values=values,
                readouts=[format_bytes(value) for value in values],
                summary=f"{format_bytes(peak_of(values))} peak",
            )
            for label, color, values in present
        ],
        caption=f"{subtitle[:1].upper()}{subtitle[1:]}.{resolution}",
    )


def _when(moment: float, *, started: float | None) -> str:
    since = f"+{elapsed_label(moment)}"
    return since if started is None else f"{clock(started + moment)} · {since}"


def _floats(values: Sequence[int | None]) -> list[float | None]:
    return [None if value is None else float(value) for value in values]


# -- who was responsible -------------------------------------------------------


def _consumers(summary: Record) -> list[Section]:
    by_cpu = as_records(summary.get("top_by_cpu"))[: HTML.ranking_rows]
    by_memory = as_records(summary.get("top_by_memory"))[: HTML.ranking_rows]
    if not by_cpu and not by_memory:
        return []
    return [
        Section(
            title="Biggest consumers",
            intro="Totals over the whole run, not a single moment.",
            rankings=[
                Ranking(
                    title="By CPU time",
                    entries=[
                        Ranked(
                            process=_process(row),
                            value=as_float(row.get("cpu_seconds")) or 0.0,
                            text=format_seconds(as_float(row.get("cpu_seconds"))),
                        )
                        for row in by_cpu
                    ],
                ),
                Ranking(
                    title="By peak memory (rss)",
                    entries=[
                        Ranked(
                            process=_process(row),
                            value=as_float(row.get("peak_rss_bytes")) or 0.0,
                            text=format_bytes(as_float(row.get("peak_rss_bytes"))),
                        )
                        for row in by_memory
                    ],
                ),
            ],
        )
    ]


def _process(row: Record) -> Process:
    name = str(row.get("name") or "?")
    return Process(
        name=name,
        pid=as_int(row.get("pid")) or 0,
        command=str(row.get("cmdline") or name),
        found=discovery_group(str(row.get("via") or "-")),
    )


def _tracks(series: RunSeries) -> list[Section]:
    if not series.has_per_process:
        return []
    duration = series.duration
    total = len(series.tracks)
    shown = _shown_tracks(series.tracks)
    measure = memory_measure(series.header)
    fair = any(track.peak_pss for track in shown)
    columns = [
        Column("Started", hint="time since the run began"),
        Column("Lived", hint="from the first sample it was in to the last"),
        Column("CPU time"),
        Column("Peak rss"),
    ]
    if fair:
        columns.append(Column(f"Peak {measure.short}"))
    rows: list[Track] = []
    for track in shown:
        cells = [
            Cell(text=f"+{elapsed_label(track.first_t)}", sort=track.first_t),
            Cell(text=format_duration_compact(track.lifetime), sort=track.lifetime),
            Cell(text=format_seconds(track.cpu_seconds), sort=track.cpu_seconds),
            Cell(text=format_bytes(track.peak_rss), sort=float(track.peak_rss)),
        ]
        if fair:
            cells.append(Cell(text=format_bytes(track.peak_pss), sort=float(track.peak_pss)))
        rows.append(
            Track(
                process=Process(name=track.name, pid=track.pid, command=track.cmdline, found=track.group),
                lifetime=Lifetime(
                    start=track.first_t / duration if duration else 0.0,
                    end=track.last_t / duration if duration else 1.0,
                    label=(
                        f"seen from +{elapsed_label(track.first_t)} to +{elapsed_label(track.last_t)} "
                        f"({format_seconds(track.lifetime)})"
                    ),
                ),
                cells=cells,
            )
        )
    note = ""
    if total > len(shown):
        half = HTML.track_rows // 2
        note = (
            f"Showing {len(shown)} of {total} processes: the {half} that used the most CPU time and the "
            f"{half} that held the most memory. Every process counts in the figures above."
        )
    return [
        Section(
            title="Process tracks",
            intro=(
                "Every process the run was made of, earliest first. Matched is the process treehawk was "
                "pointed at, child was found through its parent, detached was recognised after it left the tree. "
                "Click a column to sort by it."
            ),
            table=Tracks(columns=columns, rows=rows, total=total, axis=("0", elapsed_label(duration)), note=note),
        )
    ]


def _shown_tracks(tracks: Sequence[ProcessTrack]) -> list[ProcessTrack]:
    """Every track when they fit; otherwise the biggest by CPU and by memory, half each."""
    if len(tracks) <= HTML.track_rows:
        return list(tracks)
    half = HTML.track_rows // 2
    chosen = {id(track): track for track in sorted(tracks, key=lambda track: track.cpu_seconds, reverse=True)[:half]}
    for track in sorted(tracks, key=lambda track: track.peak_rss, reverse=True):
        if len(chosen) >= HTML.track_rows:
            break
        chosen.setdefault(id(track), track)
    return sorted(chosen.values(), key=lambda track: (track.first_t, track.pid))


# -- the details ---------------------------------------------------------------


def _facts(*, series: RunSeries, summary: Record, started: float | None, log: str) -> list[Fact]:
    header = series.header
    host = as_mapping(header.get("host"))
    measure = memory_measure(header)
    mode = str(header.get("mode") or "?")
    matcher = as_mapping(header.get("matcher"))
    duration = series.duration
    asleep = f", {format_seconds(series.asleep_s)} of it asleep" if series.sleeps else ""
    overruns = as_int(summary.get("overruns")) or 0
    code = as_int(summary.get("exit_code"))
    boundary = header.get("group_path")
    facts = [
        Fact("Command" if mode == "run" else "Watching", target_of(header), mono=True),
        Fact(
            "Mode",
            "run: started by treehawk"
            if mode == "run"
            else f"{mode}: found by {matcher.get('kind', '?')} {matcher.get('value', '')}".rstrip(),
        ),
        Fact("Started", stamp(started) if started is not None else "-"),
        Fact("Ended", stamp(started + duration) if started is not None else "-"),
        Fact("Duration", f"{format_seconds(duration)}{asleep}"),
        Fact("Exit code", "-" if code is None else f"{code} ({_exit_text(code)})" if code < 0 else str(code)),
        Fact(
            "Sampling",
            f"every {series.interval:g}s, {summary.get('samples', len(series.t))} samples"
            + (f", {overruns} late" if overruns else ", none late"),
        ),
        Fact(
            "Host",
            f"{host.get('hostname', '?')} · {platform_name(host.get('platform'))} · {series.ncpu} cores · "
            f"{format_bytes(as_float(host.get('mem_total_bytes')))} memory",
        ),
        Fact(
            "Boundary",
            str(boundary) if boundary else "none: membership inferred from the process table",
            mono=bool(boundary),
        ),
        Fact("Followed", ", ".join(str(name) for name in as_sequence(header.get("expand"))) or "-"),
        Fact("Memory measure", f"{measure.long}: {measure.blurb}"),
    ]
    source = header.get("metric_source")
    if source:
        facts.append(Fact("Readings from", str(source), mono=True))
    facts.extend(
        (
            Fact("CPU time", format_seconds(as_float(summary.get("cpu_seconds_used")))),
            Fact("Log", log, mono=True),
            Fact(
                "Written by", f"treehawk {header.get('treehawk_version', '?')}, log schema {header.get('schema', '?')}"
            ),
        )
    )
    return facts
