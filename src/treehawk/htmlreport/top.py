def _charts(*, series: TopSeries, first: float, last: float) -> list[Chart]:
    """The machine's own CPU and memory - or, where the platform reports neither,
    the top processes' summed, said plainly so it is not read as the machine."""
    history = series.history
    span = last - first
    machine = peak_of(series.host_cpu) is not None or peak_of(series.host_memory) is not None
    columns = (
        [series.host_cpu, series.host_memory]
        if machine
        else [_summed(series.process_cpu.values()), _summed(series.process_rss.values())]
    )
    seconds = [series.started + hours * 3600.0 for hours in series.t]
    x, (cpu, memory) = with_breaks(x=seconds, columns=columns, gap=series.bucket_seconds * HTML.gap_points)
    axis = Axis(
        x=[(moment - first) / span if span else 0.0 for moment in x],
        when=[clock_label(moment, span=span, step=1.0) for moment in x],
        ticks=clock_ticks(first, last),
        bands=[],
    )
    resolution = f" Each point is the peak of {format_seconds(series.bucket_seconds)}."
    top_n = history.header.get("top_n", "N")

    if machine:
        cpu_chart = chart(
            axis=axis,
            title="CPU, whole machine",
            unit=Unit.PERCENT,
            peak=100.0 / HTML.headroom,
            lines=[_line(label="cpu", color="s1", values=cpu, unit=Unit.PERCENT)],
            caption=f"Busy share of every core together: 100% is the whole machine.{resolution}",
        )
        if history.mean_host_cpu_percent is not None:
            mean = history.mean_host_cpu_percent
            cpu_chart.rules.append(Rule(value=mean, label=f"mean {format_percent(mean)}"))
    else:
        cpu_chart = chart(
            axis=axis,
            title=f"CPU, top {top_n} processes together",
            unit=Unit.PERCENT,
            peak=peak_of(cpu),
            lines=[_line(label="cpu", color="s1", values=cpu, unit=Unit.PERCENT)],
            caption=(
                "This platform reports no machine-wide figure, so this sums the processes that were ranked; "
                f"100% is one core fully busy.{resolution}"
            ),
        )
    cpu_chart.marks.extend(_marks(history.events, resource=Resource.CPU, first=first, span=span))

    total = as_float(as_mapping(history.header.get("host")).get("mem_total_bytes"))
    if machine:
        memory_chart = chart(
            axis=axis,
            title="Memory in use, whole machine",
            unit=Unit.BYTES,
            peak=max(total or 0.0, peak_of(memory) or 0.0) / HTML.headroom if total else peak_of(memory),
            lines=[_line(label="in use", color="s3", values=memory, unit=Unit.BYTES)],
            caption=f"Memory the system counts as used, out of everything installed.{resolution}",
        )
        if total:
            memory_chart.rules.append(Rule(value=total, label=f"installed {format_bytes(total)}"))
    else:
        memory_chart = chart(
            axis=axis,
            title=f"Memory, top {top_n} processes together",
            unit=Unit.BYTES,
            peak=peak_of(memory),
            lines=[_line(label="rss", color="s3", values=memory, unit=Unit.BYTES)],
            caption=f"Summed rss of the ranked processes; shared pages count once per process.{resolution}",
        )
    memory_chart.marks.extend(_marks(history.events, resource=Resource.MEMORY, first=first, span=span))
    return [cpu_chart, memory_chart]


def _line(*, label: str, color: str, values: list[float | None], unit: Unit) -> Line:
    shown = format_percent if unit is Unit.PERCENT else format_bytes
    return Line(
        label=label,
        color=color,
        values=values,
        readouts=[shown(value) for value in values],
        summary=f"{shown(peak_of(values))} peak",
        fill=True,
    )


def _summed(columns: Iterable[Sequence[float | None]]) -> list[float | None]:
    """Each time bucket's readings added up; None where no process had one."""
    total: list[float | None] = []
    for column in columns:
        if not total:
            total = [None] * len(column)
        for index, value in enumerate(column):
            if value is not None:
                total[index] = (total[index] or 0.0) + value
    return total


def _marks(events: Sequence[Record], *, resource: Resource, first: float, span: float) -> list[Mark]:
    if not span:
        return []
    marks: list[Mark] = []
    for event in events:
        when = as_float(event.get("time"))
        kind = event.get("kind")
        if when is None:
            continue
        if kind == str(EventKind.SPIKE) and event.get("resource") == str(resource):
            level = Level.CRITICAL
        elif kind == str(EventKind.CREEP) and resource is Resource.MEMORY:
            level = Level.WARNING
        else:
            continue
        label = f"{kind} · {event.get('name', '?')} ({event.get('pid', '?')}) · {clock(when)}"
        marks.append(Mark(position=(when - first) / span, level=level, label=label))
    return marks


# -- who did it ----------------------------------------------------------------


def _process(entry: ProcessHistory) -> Process:
    return Process(name=entry.name, pid=entry.pid, command=entry.cmdline)


def _consumers(series: TopSeries) -> Section:
    processes = list(series.history.processes.values())
    by_cpu = sorted(processes, key=lambda entry: entry.cpu_seconds, reverse=True)[: HTML.ranking_rows]
    by_memory = sorted(processes, key=lambda entry: entry.peak_rss_bytes, reverse=True)[: HTML.ranking_rows]
    return Section(
        title="Biggest consumers",
        intro=(
            "CPU time counts only while a process was in the top N, so a daemon that idles for a month does not lead."
        ),
        rankings=[
            Ranking(
                title="By CPU time while ranked",
                entries=[
                    Ranked(process=_process(entry), value=entry.cpu_seconds, text=format_seconds(entry.cpu_seconds))
                    for entry in by_cpu
                ],
            ),
            Ranking(
                title="By peak memory (rss)",
                entries=[
                    Ranked(
                        process=_process(entry),
                        value=float(entry.peak_rss_bytes),
                        text=format_bytes(entry.peak_rss_bytes),
                    )
                    for entry in by_memory
                ],
            ),
        ],
    )


def _events(series: TopSeries) -> list[Section]:
    events = sorted(series.history.events, key=lambda event: as_float(event.get("time")) or 0.0, reverse=True)
    if not events:
        return []
    shown = events[: HTML.event_rows]
    rows: list[list[Cell]] = []
    for event in shown:
        kind = str(event.get("kind", "?"))
        resource = str(event.get("resource") or "")
        when = as_float(event.get("time")) or 0.0
        name = f"{event.get('name', '?')} ({event.get('pid', '?')})"
        if kind == str(EventKind.CREEP):
            reached = format_bytes(as_float(event.get("value")))
            usual = f"rising {format_bytes(as_float(event.get('slope_per_hour')))}/h"
            level = Level.WARNING
        else:
            reached = format_value(resource, as_float(event.get("value")))
            usual = f"usually {format_value(resource, as_float(event.get('baseline')))}"
            level = Level.CRITICAL
        rows.append(
            [
                Cell(text=stamp(when), sort=when),
                Cell(
                    text="leak suspect" if kind == str(EventKind.CREEP) else f"{_resource_name(resource)} spike",
                    sort=kind,
                ),
                Cell(text=name, sort=name.lower()),
                Cell(text=reached, sort=as_float(event.get("value")) or 0.0, level=level),
                Cell(text=usual, sort=usual),
            ]
        )
    intro = "Latest first."
    if len(events) > len(shown):
        intro = f"The latest {len(shown)} of {len(events)}."
    return [
        Section(
            title=f"Events ({len(events)})",
            intro=f"{intro} A spike is a reading far above that process' own recent baseline; a leak suspect is "
            "memory that kept rising for half an hour or more.",
            events=rows,
            event_columns=[
                Column("When", numeric=False),
                Column("What", numeric=False),
                Column("Process", numeric=False),
                Column("Reached"),
                Column("Compared with", numeric=False),
            ],
        )
    ]


def _resource_name(resource: str) -> str:
    return {str(Resource.CPU): "cpu", str(Resource.MEMORY): "memory", str(Resource.GPU): "gpu"}.get(resource, resource)


def _tracks(*, series: TopSeries, first: float, last: float) -> Section:
    span = last - first
    processes = sorted(series.history.processes.values(), key=lambda entry: (entry.first_seen, entry.pid))
    shown = _shown(processes)
    rows = [
        Track(
            process=_process(entry),
            lifetime=Lifetime(
                start=(entry.first_seen - first) / span if span else 0.0,
                end=(entry.last_seen - first) / span if span else 1.0,
                label=f"in the top from {stamp(entry.first_seen)} to {stamp(entry.last_seen)}",
            ),
            cells=[
                Cell(text=clock_label(entry.first_seen, span=span, step=1.0), sort=entry.first_seen),
                Cell(
                    text=format_duration_compact(entry.last_seen - entry.first_seen),
                    sort=entry.last_seen - entry.first_seen,
                ),
                Cell(text=format_seconds(entry.cpu_seconds), sort=entry.cpu_seconds),
                Cell(text=format_percent(entry.peak_cpu_percent), sort=entry.peak_cpu_percent),
                Cell(text=format_bytes(entry.peak_rss_bytes), sort=float(entry.peak_rss_bytes)),
                Cell(
                    text=f"{format_bytes(entry.first_rss_bytes)} → {format_bytes(entry.last_rss_bytes)}",
                    sort=float(entry.last_rss_bytes - entry.first_rss_bytes),
                ),
            ],
        )
        for entry in shown
    ]
    note = ""
    if len(processes) > len(shown):
        half = HTML.track_rows // 2
        note = (
            f"Showing {len(shown)} of {len(processes)} processes: the {half} that used the most CPU time and "
            f"the {half} that held the most memory."
        )
    return Section(
        title="Process tracks",
        intro=(
            "Every process that reached the top, earliest first. The bar runs from the first sample it was "
            "ranked in to the last. Click a column to sort by it."
        ),
        table=Tracks(
            columns=[
                Column("First seen"),
                Column("Span"),
                Column("CPU time", hint="while in the top N"),
                Column("Peak CPU"),
                Column("Peak rss"),
                Column("Memory", hint="rss when first and last seen; sorts by growth"),
            ],
            rows=rows,
            total=len(processes),
            axis=(clock_label(first, span=span), clock_label(last, span=span)),
            note=note,
        ),
    )


def _shown(processes: Sequence[ProcessHistory]) -> list[ProcessHistory]:
    """Every process when they fit; otherwise the biggest by CPU and by memory, half each."""
    if len(processes) <= HTML.track_rows:
        return list(processes)
    half = HTML.track_rows // 2
    by_cpu = sorted(processes, key=lambda entry: entry.cpu_seconds, reverse=True)
    chosen = {entry.identity: entry for entry in by_cpu[:half]}
    for entry in sorted(processes, key=lambda entry: entry.peak_rss_bytes, reverse=True):
        if len(chosen) >= HTML.track_rows:
            break
        chosen.setdefault(entry.identity, entry)
    return sorted(chosen.values(), key=lambda entry: (entry.first_seen, entry.pid))


def _facts(*, series: TopSeries, first: float, last: float, log: str) -> list[Fact]:
    history = series.history
    header = history.header
    host = as_mapping(header.get("host"))
    counts = history.event_counts
    return [
        Fact(
            "Host",
            f"{host.get('hostname', '?')} · {platform_name(host.get('platform'))} · {host.get('ncpu', '?')} cores · "
            f"{format_bytes(as_float(host.get('mem_total_bytes')))} memory",
        ),
        Fact("From", stamp(first)),
        Fact("To", stamp(last)),
        Fact("Covered", format_seconds(last - first)),
        Fact("Followed", f"top {header.get('top_n', '?')} by cpu and by memory, every sample"),
        Fact("Samples", f"{history.samples} in {history.segments} log file(s), {history.overruns} late"),
        Fact("Chart resolution", f"one point per {format_seconds(series.bucket_seconds)}, the peak of each"),
        Fact(
            "Entries / exits",
            f"{counts.get(str(EventKind.ENTER), 0)} / {counts.get(str(EventKind.LEAVE), 0)} of the top",
        ),
        Fact("Boot", str(header.get("boot_id") or "-"), mono=True),
        Fact("Log", log, mono=True),
        Fact("Written by", f"treehawk {header.get('treehawk_version', '?')}, log schema {header.get('schema', '?')}"),
    ]
