"""The HTML page for a ``top`` log: what a whole machine did, and who did it.

Laid out like the workload page, on a wall-clock axis: a ``top`` log can span
days and several boots, and only the clock orders them.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from treehawk import __version__
from treehawk.charts.models import TopSeries
from treehawk.core.humanize import format_bytes, format_duration_compact, format_percent, format_seconds
from treehawk.core.interfaces import Record
from treehawk.core.values import as_float, as_mapping, as_sequence
from treehawk.htmlreport.constants import HTML
from treehawk.htmlreport.models import (
    Cell,
    Chart,
    Column,
    Fact,
    Figure,
    Level,
    Lifetime,
    Line,
    Mark,
    Notice,
    Page,
    Process,
    Ranked,
    Ranking,
    Rule,
    Section,
    Track,
    Tracks,
    Unit,
)
from treehawk.htmlreport.parts import Axis, chart, peak_of, platform_name
from treehawk.htmlreport.scale import clock, clock_label, clock_ticks, day, stamp, with_breaks
from treehawk.top.history import leak_suspects
from treehawk.top.models import EventKind, ProcessHistory, Resource
from treehawk.ui.top_views import format_value


def top_page(
    *,
    series: TopSeries,
    log_path: str,
    generated: float,
    since: float | None = None,
    until: float | None = None,
) -> Page:
    """The page for a ``top`` log, over the window ``since`` to ``until``."""
    history = series.history
    host = as_mapping(history.header.get("host"))
    hostname = str(host.get("hostname") or "this machine")
    first = history.first_time or series.started
    last = history.last_time or first
    return Page(
        title=f"{hostname} · treehawk machine report",
        kind="machine",
        headline=hostname,
        status=_status(series=series, since=since, until=until),
        span=[
            Figure(label="From", value=clock(first), detail=day(first)),
            Figure(label="To", value=clock(last), detail=day(last)),
            Figure(
                label="Covered",
                value=format_duration_compact(last - first),
                detail=f"{history.samples} samples",
            ),
        ],
        figures=_figures(series),
        notices=_notices(series),
        sections=[
            Section(
                title="Timeline",
                intro=(
                    "Hover over a chart to read it at that moment; ticks along the bottom mark spikes and leak reports."
                ),
                charts=_charts(series=series, first=first, last=last),
            ),
            _consumers(series),
            *_events(series),
            _tracks(series=series, first=first, last=last),
            Section(title="Details", facts=_facts(series=series, first=first, last=last, log=log_path)),
        ],
        footer=f"Generated by treehawk {__version__} on {stamp(generated)} from {log_path}",
    )


def _status(*, series: TopSeries, since: float | None, until: float | None) -> list[Notice]:
    header = series.history.header
    host = as_mapping(header.get("host"))
    pacing = str(header.get("pacing") or "")
    interval = as_float(header.get("interval"))
    chips = [
        Notice(level=Level.NOTE, title=platform_name(host.get("platform"))),
        Notice(level=Level.NOTE, title=f"top {header.get('top_n', '?')}", text="processes followed by cpu and memory"),
        Notice(
            level=Level.NOTE,
            title="as often as it can" if pacing == "auto" else f"every {interval or 0:g}s",
            text="the sampling interval",
        ),
        Notice(level=Level.NOTE, title=f"{series.history.segments} log file(s)"),
    ]
    if since is not None or until is not None:
        chips.append(Notice(level=Level.WARNING, title="window", text="--since / --until cut the log to this window"))
    return chips


def _figures(series: TopSeries) -> list[Figure]:
    history = series.history
    total = as_float(as_mapping(history.header.get("host")).get("mem_total_bytes"))
    spikes = [event for event in history.events if event.get("kind") == str(EventKind.SPIKE)]
    cpu_spikes = sum(1 for event in spikes if event.get("resource") == str(Resource.CPU))
    figures: list[Figure] = []
    # Left out, not shown as a dash, where the platform has no machine-wide figure.
    if history.peak_host_cpu_percent is not None:
        figures.append(
            Figure(
                label="Peak CPU",
                value=format_percent(history.peak_host_cpu_percent),
                detail=f"of all cores · mean {format_percent(history.mean_host_cpu_percent)}",
            )
        )
    if history.peak_host_mem_used_bytes is not None:
        figures.append(
            Figure(
                label="Peak memory",
                value=format_bytes(history.peak_host_mem_used_bytes),
                detail=f"in use, of {format_bytes(total)}" if total else "in use",
            )
        )
    figures.extend(
        (
            Figure(label="Processes", value=str(len(history.processes)), detail="reached the top at some point"),
            Figure(
                label="Spikes", value=str(len(spikes)), detail=f"{cpu_spikes} cpu · {len(spikes) - cpu_spikes} memory"
            ),
            Figure(
                label="Leak suspects",
                value=str(len(leak_suspects(history.events))),
                detail="memory rising steadily",
            ),
        )
    )
    return figures


def _notices(series: TopSeries) -> list[Notice]:
    history = series.history
    notices = [
        Notice(
            level=Level.WARNING,
            title=(
                f"{event.get('name', '?')} ({event.get('pid', '?')}) may be leaking: memory rising "
                f"{format_bytes(as_float(event.get('slope_per_hour')))}/h"
            ),
            text=(
                f"Its floor grew from {format_bytes(as_float(event.get('baseline')))} to "
                f"{format_bytes(as_float(event.get('value')))}, steadily (fit r² "
                f"{as_float(event.get('r2')) or 0:.2f}); last reported {stamp(as_float(event.get('time')) or 0.0)}."
            ),
        )
        for event in leak_suspects(history.events)
    ]
    if history.overruns:
        notices.append(
            Notice(
                level=Level.WARNING,
                title=f"{history.overruns} of {history.samples} samples arrived late",
                text="The interval is too short for this machine; a longer one (--interval) gives the sampler room.",
            )
        )
    notices.extend(Notice(level=Level.NOTE, title=str(note)) for note in as_sequence(history.header.get("notes")))
    return notices


